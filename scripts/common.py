"""Shared constants: mapping between the Fortran loop indices and the physical
parameters used in the paper, and the repository paths.

Fortran loop index        -> paper parameter
  sml_size = 1..6         -> islet radius is_size = 1.2*sml_size + 3.8 (lattice units)
                             -> number of cells N (CELLS) -> diameter label D (D_UM)
  b_ratio  = 1..6         -> beta-cell percentage P_beta = 10*b_ratio  (%)
  epp      = 1..3         -> coupling K = 0.4*(epp-1) = 0, 0.4, 0.8
                             (the output file name carries ep = epp-1 = 0, 1, 2)
  nt       = 1..3         -> realization index
"""
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DATA = REPO / "data"
RESULTS = REPO / "results"

# Number of cells generated by init_structure for each sml_size (HCP lattice,
# lattice constant 4, radius is_size).  Deterministic: does not depend on the seed.
CELLS = {1: 743, 2: 1405, 3: 2403, 4: 3791, 5: 5563, 6: 7881}

# Diameter label D = 2 * 5.1 um * N^(1/3), rounded to the nearest micrometre
# (the cell-number-to-diameter conversion used in the paper).  Legacy analysis tables wrote 202
# for the largest islet; 2*5.1*7881^(1/3) = 203.0, which is used here.  D only
# enters the analysis as an ordered category, so this does not change any result.
D_UM = {k: int(round(2 * 5.1 * n ** (1 / 3))) for k, n in CELLS.items()}
assert list(D_UM.values()) == [92, 114, 137, 159, 181, 203]

# Simulation batches: they differ only in the high-phase input coefficient X
# (Fortran line  st = X*extamp*g0  for 60 < t <= 120 min).
# Nominal high-phase glucose G_high/G0 = 1 + 2X  (G0 = 7 mM).
BATCHES = {"0123": 0.2, "1011": 0.4, "1204": 0.6, "1009": 0.8}
G0_MM = 7.0

# Glucose phases of the 200-min protocol and the rows of the 2000-line output
# that are averaged to get the IPA (one row = 0.1 min; row r <-> t = 0.1*(r+1)).
PHASES = {                      # name: (first row, last row + 1, time window)
    "normal": (0, 600, "0-60 min"),
    "high": (600, 1200, "60-120 min"),
    "low": (1400, 2000, "140-200 min"),
}
LOW_INPUT = -0.2                # low-phase coefficient (same in every batch)


def g_label(phase, x):
    """Nominal G/G0 label of a phase: 1 + 2*coefficient (fixed point of
    dg/dt = I + g0*ha - g*hb with unit hormone output and extamp = 2)."""
    coef = {"normal": 0.0, "high": x, "low": LOW_INPUT}[phase]
    return round(1 + 2 * coef, 1)


def k_from_ep(ep):
    """File-name ep (= epp-1) -> coupling K."""
    return round(0.4 * ep, 1)
